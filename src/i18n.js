const messages = { zh, en }

export function lang() {
  return progress.settings.lang
}

export function hasKey(key) {
  return key in zh
}

// 不替换参数的原文：列步骤那句话要在 {scale}、{number} 的位置放上可以点的空
export function template(key) {
  return messages[progress.settings.lang]?.[key] ?? zh[key] ?? key
}

export function t(key, params = {}) {
  const text = messages[progress.settings.lang]?.[key] ?? zh[key] ?? key
  return text.replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? '').toString())
}
